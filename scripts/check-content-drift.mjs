#!/usr/bin/env node
/**
 * Fails when the bundled grammar no longer matches what docs.micropage.sh
 * serves (the docs site is the source of truth). Also checks the bundled
 * copies against ../docs/static when run inside the monorepo, which catches a
 * forgotten `npm run sync-content` before the docs are even deployed.
 *
 *   npm run check-content            # network failure warns, exits 0
 *   npm run check-content -- --strict  # network failure is an error too
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MCP_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(MCP_DIR, "..");
const strict = process.argv.includes("--strict");
const TIMEOUT_MS = 15_000;

const FILES = [
  { bundled: "src/content/grammar.md", url: "https://docs.micropage.sh/llms.txt", local: "docs/static/llms.txt" },
  {
    bundled: "src/content/grammar-full.md",
    url: "https://docs.micropage.sh/llms-full.txt",
    local: "docs/static/llms-full.txt",
  },
];

const normalise = (s) => s.replace(/\r\n?/g, "\n").trim();

// Strip the generated-file header sync-content.mjs prepends.
const bundledText = (path) =>
  normalise(readFileSync(join(MCP_DIR, path), "utf8").replace(/^<!-- Generated by [^\n]*-->\n\n/, ""));

function firstDifference(a, b) {
  const al = a.split("\n");
  const bl = b.split("\n");
  for (let i = 0; i < Math.max(al.length, bl.length); i++) {
    if (al[i] !== bl[i]) {
      return `line ${i + 1}:\n    bundled: ${JSON.stringify(al[i] ?? "<end of file>")}\n    other:   ${JSON.stringify(bl[i] ?? "<end of file>")}`;
    }
  }
  return "no line differs (whitespace only)";
}

let drift = 0;
let networkErrors = 0;

for (const f of FILES) {
  const bundled = bundledText(f.bundled);

  const localPath = join(ROOT, f.local);
  if (existsSync(localPath)) {
    const local = normalise(readFileSync(localPath, "utf8"));
    if (local === bundled) {
      console.log(`ok     ${f.bundled} matches ${f.local}`);
    } else {
      drift++;
      console.error(
        `DRIFT  ${f.bundled} differs from ${f.local} (run npm run sync-content)\n  ${firstDifference(bundled, local)}`,
      );
    }
  }

  let remote;
  try {
    const res = await fetch(f.url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    remote = normalise(await res.text());
  } catch (err) {
    networkErrors++;
    const msg = `could not fetch ${f.url}: ${err instanceof Error ? err.message : String(err)}`;
    console[strict ? "error" : "warn"](`${strict ? "ERROR" : "warn "}  ${msg}`);
    continue;
  }

  if (remote === bundled) {
    console.log(`ok     ${f.bundled} matches ${f.url}`);
  } else {
    drift++;
    console.error(
      `DRIFT  ${f.bundled} differs from ${f.url}\n  ${firstDifference(bundled, remote)}\n` +
        `  The docs site is the source of truth. If docs/static is newer, deploy the docs; ` +
        `then run npm run sync-content here.`,
    );
  }
}

if (drift > 0) {
  console.error(`\ncheck-content: ${drift} drift(s) found.`);
  process.exit(1);
}
if (networkErrors > 0 && strict) {
  console.error(`\ncheck-content: ${networkErrors} fetch failure(s) with --strict.`);
  process.exit(1);
}
console.log(networkErrors > 0 ? "\ncheck-content: no drift found offline; remote not checked." : "\ncheck-content: OK");
